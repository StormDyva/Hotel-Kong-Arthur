-- Fresh PostgreSQL baseline for T-032. MySQL v1 migrations are retained separately.

CREATE TABLE room_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(120) NOT NULL,
    capacity SMALLINT NOT NULL,
    base_price_low_season DECIMAL(10, 2) NOT NULL,
    base_price_mid_season DECIMAL(10, 2) NOT NULL,
    base_price_high_season DECIMAL(10, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_room_types_name UNIQUE (name),
    CONSTRAINT chk_room_types_capacity CHECK (capacity BETWEEN 1 AND 4),
    CONSTRAINT chk_room_types_prices CHECK (
        base_price_low_season >= 0
        AND base_price_mid_season >= 0
        AND base_price_high_season >= 0
    )
);

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    room_number VARCHAR(20) NOT NULL,
    room_type_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_rooms_room_number UNIQUE (room_number),
    CONSTRAINT fk_rooms_room_type
        FOREIGN KEY (room_type_id) REFERENCES room_types (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE guests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    country_code CHAR(2) NOT NULL,
    country_name VARCHAR(120) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    guest_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    check_in DATE NOT NULL,
    check_out DATE NOT NULL,
    guests_count SMALLINT NOT NULL,
    price_total DECIMAL(12, 2) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'DKK',
    status VARCHAR(40) CHECK (status IN ('confirmed', 'cancelled')) NOT NULL DEFAULT 'confirmed',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_bookings_guest
        FOREIGN KEY (guest_id) REFERENCES guests (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_bookings_room
        FOREIGN KEY (room_id) REFERENCES rooms (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT chk_bookings_dates CHECK (check_out > check_in),
    CONSTRAINT chk_bookings_guests_count CHECK (guests_count >= 1),
    CONSTRAINT chk_bookings_price_total CHECK (price_total >= 0),
    CONSTRAINT chk_bookings_currency CHECK (currency = 'DKK')
);

CREATE TABLE bar_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(160) NOT NULL,
    category VARCHAR(40) CHECK (category IN ('cocktail', 'coffee', 'other')) NOT NULL,
    price DECIMAL(10, 2) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_bar_products_name UNIQUE (name),
    CONSTRAINT chk_bar_products_price CHECK (price >= 0)
);

CREATE TABLE bar_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_id BIGINT NOT NULL,
    sold_at TIMESTAMP NOT NULL,
    quantity BIGINT NOT NULL,
    unit_price DECIMAL(10, 2) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'DKK',
    employee_name VARCHAR(160) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_bar_sales_product
        FOREIGN KEY (product_id) REFERENCES bar_products (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT chk_bar_sales_quantity CHECK (quantity >= 1),
    CONSTRAINT chk_bar_sales_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_bar_sales_currency CHECK (currency = 'DKK')
);

CREATE TABLE seasons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(40) NOT NULL,
    name VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_seasons_code UNIQUE (code),
    CONSTRAINT uq_seasons_name UNIQUE (name)
);

CREATE TABLE season_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    season_id BIGINT NOT NULL,
    start_month SMALLINT NOT NULL,
    start_day SMALLINT NOT NULL,
    end_month SMALLINT NOT NULL,
    end_day SMALLINT NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_season_period UNIQUE (season_id, start_month, start_day, end_month, end_day),
    CONSTRAINT fk_season_periods_season
        FOREIGN KEY (season_id) REFERENCES seasons (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT chk_season_periods_months CHECK (
        start_month BETWEEN 1 AND 12
        AND end_month BETWEEN 1 AND 12
    ),
    CONSTRAINT chk_season_periods_days CHECK (
        start_day BETWEEN 1 AND 31
        AND end_day BETWEEN 1 AND 31
    )
);

CREATE TABLE room_type_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    room_type_id BIGINT NOT NULL,
    season_id BIGINT NOT NULL,
    price_per_night DECIMAL(10, 2) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'DKK',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_room_type_price_season UNIQUE (room_type_id, season_id),
    CONSTRAINT fk_room_type_prices_room_type
        FOREIGN KEY (room_type_id) REFERENCES room_types (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_room_type_prices_season
        FOREIGN KEY (season_id) REFERENCES seasons (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT chk_room_type_prices_amount CHECK (price_per_night >= 0),
    CONSTRAINT chk_room_type_prices_currency CHECK (currency = 'DKK')
);

CREATE TABLE booking_price_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    booking_id BIGINT NOT NULL,
    night_date DATE NOT NULL,
    season_id BIGINT NOT NULL,
    price_per_night DECIMAL(10, 2) NOT NULL,
    quantity SMALLINT NOT NULL DEFAULT 1,
