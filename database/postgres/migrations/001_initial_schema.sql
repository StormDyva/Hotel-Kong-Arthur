    PRIMARY KEY (id),
    CONSTRAINT uq_booking_price_line_night UNIQUE (booking_id, night_date),
    CONSTRAINT fk_booking_price_lines_booking
        FOREIGN KEY (booking_id) REFERENCES bookings (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_booking_price_lines_season
        FOREIGN KEY (season_id) REFERENCES seasons (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT chk_booking_price_lines_price CHECK (price_per_night >= 0),
    CONSTRAINT chk_booking_price_lines_quantity CHECK (quantity >= 1),
    CONSTRAINT chk_booking_price_lines_total CHECK (line_total >= 0),
    CONSTRAINT chk_booking_price_lines_currency CHECK (currency = 'DKK')
);

CREATE TABLE import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_system VARCHAR(160) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_sha256 CHAR(64) NOT NULL,
    imported_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    row_count BIGINT NOT NULL,
    accepted_count BIGINT NOT NULL,
    rejected_count BIGINT NOT NULL,
    status VARCHAR(40) CHECK (status IN ('completed', 'completed_with_rejections', 'failed')) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_import_batches_file UNIQUE (source_system, file_name, file_sha256),
    CONSTRAINT chk_import_batches_counts CHECK (
        accepted_count + rejected_count = row_count
    )
);

