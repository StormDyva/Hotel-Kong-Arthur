CREATE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at := clock_timestamp() AT TIME ZONE 'UTC'; RETURN NEW; END $$;
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['room_types','rooms','guests','bookings','bar_products','seasons','room_type_prices','booking_reviews'] LOOP
  EXECUTE format('CREATE TRIGGER touch_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION touch_updated_at()',t);
 END LOOP;
END $$;
CREATE FUNCTION check_booking_capacity() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE room_capacity integer;
BEGIN
 IF TG_OP = 'UPDATE' AND NEW.status = 'cancelled' THEN RETURN NEW; END IF;
 SELECT rt.capacity INTO room_capacity FROM rooms r JOIN room_types rt ON rt.id=r.room_type_id
 WHERE r.id=NEW.room_id AND r.active AND r.status='available' AND rt.active;
 IF room_capacity IS NULL THEN RAISE EXCEPTION 'room_id must reference an active, available room type' USING ERRCODE='23514'; END IF;
 IF NEW.guests_count > room_capacity THEN RAISE EXCEPTION 'guests_count exceeds room type capacity' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER bookings_capacity BEFORE INSERT OR UPDATE ON bookings FOR EACH ROW EXECUTE FUNCTION check_booking_capacity();

